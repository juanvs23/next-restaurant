import mongoose from "mongoose";

const subscriptionSchema = new mongoose.Schema(
  {
    email: {
      type: String,
      required: true,
      unique: true,
      lowercase: true,
      trim: true,
    },
  },
  { timestamps: true }
);

export const Subscription =
  (mongoose.models?.Subscription as any) ||
  mongoose.model("Subscription", subscriptionSchema);
